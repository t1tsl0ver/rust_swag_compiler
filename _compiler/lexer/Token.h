#pragma once

#include <string>
#include <variant>

// Names used by parser.y intentionally match its %token declarations.
enum class TokenKind {
    End = 0,
    ABSTRACT, AMPERSAND, AS, ASSIGN, ASYNC, AT, AWAIT, BANG, BECOME,
    BIT_AND_ASSIGN, BIT_OR_ASSIGN, BIT_XOR, BIT_XOR_ASSIGN, BOX, BREAK,
    CHAR_LITERAL, COLON, COMMA, CONST, CONTINUE, CRATE, DIVIDE_ASSIGN,
    DO, DOLLAR, DOT, DYN, ELSE, ENUM, EQUAL_EQUAL, EXTERN, FALSE,
    FAT_ARROW, FINAL, FLOAT_LITERAL, FN, FOR, GREATER, GREATER_EQUAL,
    ID, IF, IMPL, IN, INTEGER_LITERAL_BIN, INTEGER_LITERAL_DEC,
    INTEGER_LITERAL_HEX, INTEGER_LITERAL_OCT, LEFT_BRACE, LEFT_BRACKET,
    LEFT_PAREN, LESS, LESS_EQUAL, LET, LOGICAL_AND, LOGICAL_OR, LOOP,
    MACRO, MATCH, MINUS, MINUS_ASSIGN, MOD, MOVE, MULTIPLY_ASSIGN,
    MUT, NOT_EQUAL, OVERRIDE, PATH_SEPARATOR, PIPE, PLUS, PLUS_ASSIGN,
    POUND, PRIV, PUB, QUESTION, RANGE, RANGE_INCLUSIVE, RAW_IDENTIFIER,
    RAW_STRING_LITERAL, REF, REMAINDER, REMAINDER_ASSIGN, RETURN,
    RIGHT_ARROW, RIGHT_BRACE, RIGHT_BRACKET, RIGHT_PAREN, SELF_TYPE,
    SELF_VALUE, SEMICOLON, SHIFT_LEFT, SHIFT_LEFT_ASSIGN, SHIFT_RIGHT,
    SHIFT_RIGHT_ASSIGN, SLASH, STAR, STATIC, STRING_LITERAL, STRUCT,
    SUPER, TILDE, TRAIT, TRUE, TRY, TYPE, TYPEOF, UNDERSCORE, UNSAFE,
    UNSIZED, USE, VIRTUAL, WHERE, WHILE, YIELD
};

using TokenValue = std::variant<std::monostate, std::string, unsigned long long, double>;

struct Token {
    TokenKind kind = TokenKind::End;
    std::string spelling;
    TokenValue value;
};
